import {estimateFcl,procurementValidity} from './cost-unified-model.js';
import {websiteQuoteDraft} from './public-quote-model.js';

const BOXES=new Map([['20尺','20GP'],['20GP','20GP'],['40HQ','40HQ'],['45尺','45HQ'],['45HQ','45HQ']]);
export const stationRailBox=row=>BOXES.get(row.quote?.container)||null;

// Only explicit box types and per-container rates; ambiguous 40尺 or 2×20尺 are reviewed separately.
export function draftableStationRail(rows,date='2026-11-01'){
 const superseded=new Set(rows.map(r=>r.supersedes_id).filter(Boolean));
 return rows.filter(r=>!superseded.has(r.id)&&r.status==='confirmed'&&r.supplier_id&&
  r.quote?.scope==='站到站'&&['SOC','COC'].includes(r.quote?.equipment)&&stationRailBox(r)&&
  (r.quote?.unit==='柜'||r.quote?.unit===stationRailBox(r))&&
  ['USD','CNY','EUR'].includes(r.quote?.currency)&&Number.isFinite(r.quote?.price)&&r.quote.price>0);
}
export function needsBalanceFee(row){
 return row.quote?.equipment==='COC'&&/平衡费.{0,80}(单询|另询|待询)/s.test(row.quote?.notes||'');
}
export function prepareStationRailQuote(row,{date,profitMode='markup',profit=15,range=5,minimum=0,balanceFee=null,otherFee=null,fx=7,eurFx=null,reviewed=false}={}){
 if(!draftableStationRail([row],date).length)throw Error('采购价格尚未确认或箱型、计价单位不适用自动定价');
 if(!reviewed)throw Error('请逐条核实报价条款及所有另计费用');
 const balance=Number(balanceFee),other=Number(otherFee);
 if(needsBalanceFee(row)&&(balanceFee===null||balanceFee===''||!Number.isFinite(balance)||balance<0))throw Error('COC平衡费需核实后填写');
 if(otherFee===null||otherFee===''||!Number.isFinite(other)||other<0)throw Error('请核实其他附加费（如确认无需另计，填写0）');
 const fees=[];
 if(needsBalanceFee(row))fees.push({name:'COC提还箱平衡费',amount:balance,currency:'USD',unit:'柜'});
 if(other>0)fees.push({name:'已确认其他附加费',amount:other,currency:'USD',unit:'柜'});
 const validity=procurementValidity(row,date);
 const input={transport:'fcl',scope:'station',station:row.origin,origin:row.origin,destination:row.destination,date,box:stationRailBox(row),quantity:1,equipment:row.quote.equipment,truck:false,rent:false,fx,eurFx,profitMode,profit,termsReviewed:true,extraFees:fees,webRange:range,webMinimum:minimum,webValidUntil:row.quote.validUntil||null};
 const calculated=estimateFcl(input,{fcl:[row]},{rail:row.id});
 if(!calculated.result.complete||calculated.result.cost<=0)throw Error('成本未完整：'+calculated.result.pending.join('；'));
 calculated.result.sourceValidityNeedsReview=validity.needsReview;
 return calculated;
}
export function stationRailSalesDraft(selected,snapshotId){
 if(!snapshotId)throw Error('请先保存成本快照');
 const draft=websiteQuoteDraft(selected,snapshotId);
 const rail=selected.inputs.sources.rail;
 draft.status='draft';
 draft.public_note='Indicative rail station-to-station price only. Inland pickup, customs, destination delivery and unlisted fees are excluded.';
 draft.pricing_meta={...draft.pricing_meta,sourceRailId:rail.id,equipment:rail.quote.equipment,checkedTerms:true,autoGenerated:'station_rail_v2'};
 return draft;
}
