import {estimateFcl} from './cost-unified-model.js';
import {websiteQuoteDraft} from './public-quote-model.js';

// First-pass automation intentionally covers unambiguous 20-foot COC station-to-station rates only.
// Other equipment and unverified 40-foot/2x20-foot formats require manual cost review.
export function draftableStationRail(rows, date='2026-11-10') {
 const superseded=new Set(rows.map(r=>r.supersedes_id).filter(Boolean));
 return rows.filter(r=>!superseded.has(r.id)&&r.status==='confirmed'&&r.supplier_id&&
  r.quote?.scope==='站到站'&&r.quote?.equipment==='COC'&&r.quote?.container==='20尺'&&
  r.quote?.unit==='柜'&&['USD','CNY','EUR'].includes(r.quote?.currency)&&
  Number.isFinite(r.quote?.price)&&r.quote.price>0&&
  r.quote.validUntil&&r.quote.validUntil>=date&&
  (!r.quote.validFrom||r.quote.validFrom<=date)&&
  (!r.quote.source?.quotationPeriod||!/^\\d{4}年\\d{1,2}月$/.test(r.quote.source.quotationPeriod)||
   date.slice(0,7)===r.quote.source.quotationPeriod.replace(/^(\\d{4})年(\\d{1,2})月$/,(all,y,m)=>y+'-'+m.padStart(2,'0'))));
}
export function needsBalanceFee(row){
 return row.quote?.equipment==='COC'&&/平衡费.{0,80}(单询|另询|待询)/s.test(row.quote?.notes||'');
}
export function prepareStationRailQuote(row,{date,profitMode='markup',profit=15,range=5,minimum=0,balanceFee=null,otherFee=0,fx=7,eurFx=null,reviewed=false}={}) {
 if(!draftableStationRail([row],date||'2026-11-10').length)throw Error('不是有效、已确认且箱型明确的20尺COC站到站采购价');
 if(!reviewed)throw Error('请先核实采购报价附加费及条款');
 const balance=Number(balanceFee),other=Number(otherFee);
 if(needsBalanceFee(row)&&(balanceFee===null||balanceFee===''||!Number.isFinite(balance)||balance<0))throw Error('需核实并填写COC平衡费金额');
 if(!Number.isFinite(other)||other<0)throw Error('其他附加费金额须为非负数');
 const fees=[];
 if(needsBalanceFee(row))fees.push({name:'COC提还箱平衡费',amount:balance,currency:'USD',unit:'柜'});
 if(other>0)fees.push({name:'已确认其他附加费',amount:other,currency:'USD',unit:'柜'});
 const input={transport:'fcl',scope:'station',station:row.origin,origin:row.origin,destination:row.destination,date,box:'20GP',quantity:1,equipment:'COC',truck:false,rent:false,fx,eurFx,profitMode,profit,termsReviewed:true,extraFees:fees,webRange:range,webMinimum:minimum,webValidUntil:row.quote.validUntil};
 const calculated=estimateFcl(input,{fcl:[row]},{rail:row.id});
 if(!calculated.result.complete||calculated.result.cost<=0)throw Error('采购成本不完整：'+calculated.result.pending.join('；'));
 return calculated;
}
export function stationRailSalesDraft(selected,snapshotId){
 if(!snapshotId)throw Error('请先保存本次完整成本快照');
 const draft=websiteQuoteDraft(selected,snapshotId);
 // Never automatically push to the public website.
 draft.status='draft';
 draft.public_note='Indicative 20GP COC station-to-station rail quotation only; inland trucking, customs, terminal handling and destination delivery are excluded unless confirmed separately.';
 draft.pricing_meta={...draft.pricing_meta,sourceRailId:selected.inputs.sources.rail.id,equipment:'COC',checkedTerms:true,autoGenerated:'station_20gp_coc_v1'};
 return draft;
}
